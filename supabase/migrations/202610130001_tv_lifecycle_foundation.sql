-- InfraHub TV lifecycle foundation
-- Apply manually in Supabase SQL Editor only after reviewing the PR.
-- Additive migration: existing TVs stay approved so current installations keep working.

begin;

alter table public.maquinas_tv
  add column if not exists hostname text,
  add column if not exists machine_uuid uuid,
  add column if not exists status_aprovacao text not null default 'aprovada',
  add column if not exists aprovada_em timestamptz,
  add column if not exists aprovada_por uuid,
  add column if not exists revogada_em timestamptz,
  add column if not exists configuracao jsonb not null default '{}'::jsonb,
  add column if not exists perfil_id uuid,
  add column if not exists ultima_atividade timestamptz,
  add column if not exists ultimo_erro text,
  add column if not exists deleted_at timestamptz,
  add column if not exists updated_at timestamptz not null default now();

alter table public.maquinas_tv
  drop constraint if exists maquinas_tv_status_aprovacao_check;
alter table public.maquinas_tv
  add constraint maquinas_tv_status_aprovacao_check
  check (status_aprovacao in ('pendente', 'aprovada', 'revogada'));

create unique index if not exists maquinas_tv_machine_uuid_unique
  on public.maquinas_tv (machine_uuid)
  where machine_uuid is not null;
create index if not exists maquinas_tv_status_aprovacao_idx
  on public.maquinas_tv (status_aprovacao);
create index if not exists maquinas_tv_deleted_at_idx
  on public.maquinas_tv (deleted_at);

alter table public.maquinas_tv_status
  add column if not exists hostname text,
  add column if not exists machine_uuid uuid,
  add column if not exists status_aprovacao text not null default 'aprovada',
  add column if not exists aprovada_em timestamptz,
  add column if not exists revogada_em timestamptz,
  add column if not exists configuracao jsonb not null default '{}'::jsonb,
  add column if not exists perfil_id uuid,
  add column if not exists ultima_atividade timestamptz,
  add column if not exists ultimo_erro text,
  add column if not exists deleted_at timestamptz;

create table if not exists public.tv_perfis_navegacao (
  id uuid primary key default gen_random_uuid(),
  nome text not null unique,
  descricao text,
  sites jsonb not null default '[]'::jsonb,
  intervalo_segundos integer not null default 30
    check (intervalo_segundos between 5 and 3600),
  ativo boolean not null default true,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  constraint tv_perfis_sites_array check (jsonb_typeof(sites) = 'array')
);

alter table public.maquinas_tv
  drop constraint if exists maquinas_tv_perfil_id_fkey;
alter table public.maquinas_tv
  add constraint maquinas_tv_perfil_id_fkey
  foreign key (perfil_id) references public.tv_perfis_navegacao(id)
  on delete set null;

alter table public.comandos
  add column if not exists status text,
  add column if not exists recebido_em timestamptz,
  add column if not exists iniciado_em timestamptz,
  add column if not exists concluido_em timestamptz,
  add column if not exists falhou_em timestamptz,
  add column if not exists prazo_em timestamptz,
  add column if not exists erro text,
  add column if not exists atualizado_em timestamptz not null default now();

update public.comandos
set status = case when executado then 'concluido' else 'enviado' end
where status is null;

alter table public.comandos
  alter column status set default 'enviado',
  alter column status set not null;
alter table public.comandos
  drop constraint if exists comandos_status_check;
alter table public.comandos
  add constraint comandos_status_check
  check (status in ('enviado', 'recebido', 'executando', 'concluido', 'falhou'));

create index if not exists comandos_maquina_status_created_idx
  on public.comandos (maquina_id, status, created_at);

-- Deliberately no FK to maquinas_tv: event history must survive TV revocation/deletion.
create table if not exists public.tv_eventos (
  id bigint generated by default as identity primary key,
  maquina_id text not null,
  machine_uuid uuid,
  hostname text,
  tipo text not null,
  nivel text not null default 'info'
    check (nivel in ('debug', 'info', 'aviso', 'erro')),
  mensagem text,
  detalhes jsonb not null default '{}'::jsonb,
  ocorrido_em timestamptz not null default now(),
  recebido_em timestamptz not null default now()
);

create index if not exists tv_eventos_maquina_ocorrido_idx
  on public.tv_eventos (maquina_id, ocorrido_em desc);
create index if not exists tv_eventos_ocorrido_idx
  on public.tv_eventos (ocorrido_em);

-- Server/service-role only. Browser clients must go through authenticated API handlers.
alter table public.tv_perfis_navegacao enable row level security;
alter table public.tv_eventos enable row level security;

-- Existing TVs retain approval and their current token. New registration handlers
-- must explicitly create records with status_aprovacao='pendente'.
-- This migration does not execute retention deletion; schedule a controlled
-- cleanup job to remove tv_eventos older than 14 days after rollout.

commit;
